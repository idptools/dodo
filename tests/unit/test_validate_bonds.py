#: One residue's atoms: name -> coordinate.
AtomSpec = Mapping[str, Sequence[float]]

#: One residue: (residue name, atoms, chain id, residue number).
ResidueSpec = tuple[str, AtomSpec, str, int]

#: Element inferred from an atom name for the synthetic builder. Only the first letter matters
#: here, and the real readers do the same thing for files with no element column.
_ELEMENTS = {"N": "N", "C": "C", "O": "O", "S": "S", "SE": "SE"}


def build(residues: Sequence[ResidueSpec]) -> Structure:
    """Assemble a structure from explicitly placed atoms.

    Coordinates in these tests are written out or derived from the reference table rather than
    generated by DODO, because the point is to control exactly which bonds are right and which
    are wrong.
    """
    xyz: list[Sequence[float]] = []
    names: list[str] = []
    elements: list[str] = []
    residue_names: list[str] = []
    residue_numbers: list[int] = []
    chain_ids: list[str] = []
    for residue_name, atoms, chain_id, number in residues:
        for atom_name, position in atoms.items():
            xyz.append(position)
            names.append(atom_name)
            elements.append(_ELEMENTS.get(atom_name[:2], _ELEMENTS.get(atom_name[:1], "C")))
            residue_names.append(residue_name)
            residue_numbers.append(number)
            chain_ids.append(chain_id)
    return Structure.from_atom_records(
        xyz=np.array(xyz, dtype=np.float64),
        atom_name=names,
        element=elements,
        residue_name=residue_names,
        residue_number=residue_numbers,
        chain_id=chain_ids,
        source="synthetic",
    )


def reference_length(residue: str, atom_a: str, atom_b: str) -> float:
    """Return the reference mean length of one bond, in Angstroms."""
    return RESIDUE_BONDS[residue][tuple(sorted((atom_a, atom_b)))][0]  # type: ignore[index]


def accepted_window(
    residue: str,
    atom_a: str,
    atom_b: str,
    *,
    sigma: float = DEFAULT_TOLERANCE_SIGMA,
    floor: float = DEFAULT_ABSOLUTE_TOLERANCE,
) -> tuple[float, float]:
    """Return the window :func:`validate_bonds` accepts for one bond, recomputed here."""
    _, sd, _, p_low, p_high = RESIDUE_BONDS[residue][tuple(sorted((atom_a, atom_b)))]  # type: ignore[index]
    slack = max(sigma * sd, floor)
    return p_low - slack, p_high + slack


def carbonyl_oxygen(carbon: Sequence[float], length: float, *, sign: float = 1.0) -> list[float]:
    """Place an oxygen on a carbon whose bond to CA runs along +x, at a CA-C-O angle of 120 deg.

    Not perpendicular, deliberately: perpendicular puts the oxygen 1.96 A from the alpha carbon,
    just inside the 1.90 A bonding cutoff plus rounding, which would make the unexpected-contact
    tests fragile for no reason. At 120 degrees it sits 2.39 A away.
    """
    return [
        carbon[0] + length * math.cos(math.radians(60.0)),
        carbon[1] + sign * length * math.sin(math.radians(60.0)),
        carbon[2],
    ]


def glycine(origin: Sequence[float] = (0.0, 0.0, 0.0)) -> AtomSpec:
    """Return a glycine whose every reference bond is exactly its measured mean.

    Glycine is the simplest complete residue -- four atoms, no ring, no side chain -- so it can be
    embedded in 3D with every bond exactly right, which makes it the baseline for "the validator
    must not flag correct geometry".
    """
    x, y, z = origin
    n = reference_length("GLY", "CA", "N")
    ca_c = reference_length("GLY", "C", "CA")
    carbon = [x + ca_c, y, z]
    return {
        "N": [x - n, y, z],
        "CA": [x, y, z],
        "C": carbon,
        "O": carbonyl_oxygen(carbon, reference_length("GLY", "C", "O")),
    }


#: Residue types whose reference bond graph is a tree, so a single residue can be embedded in 3D
#: with every bond exactly at its measured mean. The five excluded types have rings (PRO's
#: pyrrolidine, the four aromatics' side chains), and a ring cannot be built bond-by-bond from a
#: spanning tree -- the closing bond comes out wrong. Ring geometry is covered instead by the
#: fixture tests, which contain 3,000-odd real rings between them.
ACYCLIC_RESIDUES = tuple(sorted(set(RESIDUE_BONDS) - {"PRO", "HIS", "PHE", "TYR", "TRP"}))

#: Bond angle used when placing an atom relative to its parent's own bond, in degrees. Roughly
#: tetrahedral, which is what real geometry does. Placing atoms along free axes instead produces a
#: collinear chain, and then the second oxygen of a carboxylate has nowhere to go that is more than
#: 1.77 A from the first -- inside the bonding cutoff, which would trip the unexpected-contact
#: check and make these tests report the wrong thing.
_PLACEMENT_ANGLE = 112.0

#: Azimuths tried around the parent bond, in degrees.
_PLACEMENT_AZIMUTHS = tuple(range(0, 360, 20))


def _perpendicular(vector: np.ndarray) -> np.ndarray:
    """Any unit vector perpendicular to ``vector``."""
    axis = np.eye(3)[int(np.argmin(np.abs(vector)))]
    perpendicular = np.cross(vector, axis)
    return perpendicular / np.linalg.norm(perpendicular)


def _candidate_positions(
    parent: np.ndarray, incoming: np.ndarray | None, length: float
) -> list[np.ndarray]:
    """Positions ``length`` from ``parent`` at a realistic bond angle to ``incoming``."""
    if incoming is None:
        # The root has no bond to make an angle with, so try the coordinate axes.
        return [
            parent + length * direction for direction in np.concatenate([np.eye(3), -np.eye(3)])
        ]
    axial = math.cos(math.radians(180.0 - _PLACEMENT_ANGLE))
    radial = math.sin(math.radians(180.0 - _PLACEMENT_ANGLE))
    e2 = _perpendicular(incoming)
    e3 = np.cross(incoming, e2)
    return [
        parent
        + length
        * (
            axial * incoming
            + radial * (math.cos(math.radians(phi)) * e2 + math.sin(math.radians(phi)) * e3)
        )
        for phi in _PLACEMENT_AZIMUTHS
    ]


def residue_at_reference(name: str) -> AtomSpec:
    """Embed one acyclic residue with every reference bond at exactly its measured mean.

    Placement walks a spanning tree of the residue's bond graph outward from CA. Each atom goes at
    exactly its reference distance from its parent, at a tetrahedral angle to the parent's own
    bond, on whichever azimuth maximizes its distance to the nearest already-placed non-bonded
    atom. The clearance maximization matters: a residue with correct bond lengths but atoms on top
    of each other would trip the unexpected-contact check, and the test would then pass or fail for
    the wrong reason.
    """
    table = RESIDUE_BONDS[name]
    neighbours: dict[str, list[tuple[str, float]]] = {}
    for (atom_a, atom_b), (mean, *_rest) in table.items():
        if "OXT" in (atom_a, atom_b):  # a C-terminal atom; not part of the residue body
            continue
        neighbours.setdefault(atom_a, []).append((atom_b, mean))
        neighbours.setdefault(atom_b, []).append((atom_a, mean))

    placed: dict[str, np.ndarray] = {"CA": np.zeros(3)}
    incoming: dict[str, np.ndarray | None] = {"CA": None}
    order = ["CA"]
    bonded: set[frozenset[str]] = {frozenset((a, b)) for a, b in table}
    while order:
        parent = order.pop(0)
        for child, length in sorted(neighbours.get(parent, [])):
            if child in placed:
                continue
            best: tuple[float, np.ndarray] | None = None
            for candidate in _candidate_positions(placed[parent], incoming[parent], length):
                clearance = min(
                    (
                        float(np.linalg.norm(candidate - position))
                        for other, position in placed.items()
                        if frozenset((child, other)) not in bonded
                    ),
                    default=float("inf"),
                )
                if best is None or clearance > best[0]:
                    best = (clearance, candidate)
            assert best is not None, f"{name}: nowhere to put {child}"
            assert best[0] > BOND_CUTOFF, (
                f"{name}: {child} could only be placed {best[0]:.3f} A from a non-bonded atom, "
                f"inside the {BOND_CUTOFF} A bonding cutoff"
            )
            placed[child] = best[1]
            direction = best[1] - placed[parent]
            incoming[child] = direction / np.linalg.norm(direction)
            order.append(child)

    missing = {atom for pair in table for atom in pair} - set(placed) - {"OXT"}
    assert not missing, f"{name}: failed to place {sorted(missing)}"
    return {atom: position.tolist() for atom, position in sorted(placed.items())}


def ca_only_chain(
    n_residues: int = 8,
    *,
    spacing: float = CA_CA_BOND_LENGTH,
    chain: str = "A",
    first_number: int = 1,
) -> Structure:
    """Return a CA-only chain, which is exactly what a rebuilt region looks like.

    Built as a flat zig-zag rather than a straight line so that no two alpha carbons come near
    each other, which keeps these tests about bond lengths.
    """
    residues: list[ResidueSpec] = []
    step = math.sqrt(spacing**2 / 2.0)
    for i in range(n_residues):
        residues.append(("ALA", {"CA": [i * step, step * (i % 2), 0.0]}, chain, first_number + i))
    return build(residues)


def move_atom(structure: Structure, residue: int, atom: str, position: Sequence[float]) -> None:
    """Move one named atom of one residue, in place."""
    atoms = structure.atom_slice_for_residues(residue, residue + 1)
    names = [str(name) for name in structure.atom_name[atoms]]
    structure.xyz[atoms.start + names.index(atom)] = np.asarray(position, dtype=np.float64)


def stretch_bond(
    structure: Structure, residue: int, anchor: str, moved: str, length: float
) -> None:
    """Place ``moved`` at ``length`` Angstroms from ``anchor``, keeping its direction."""
    atoms = structure.atom_slice_for_residues(residue, residue + 1)
    names = [str(name) for name in structure.atom_name[atoms]]
    origin = structure.xyz[atoms.start + names.index(anchor)]
    current = structure.xyz[atoms.start + names.index(moved)]
    direction = current - origin
    direction = direction / np.linalg.norm(direction)
    structure.xyz[atoms.start + names.index(moved)] = origin + direction * length


