def test_clean_ca_only_trace_is_valid() -> None:
    structure = ca_only_chain(10)
    report = validate_bonds(structure)
    assert report.ok, report.describe()
    assert bool(report) is True
    assert report.n_ca_ca_checked == 9
    assert report.n_intra_checked == 0
    assert report.n_peptide_checked == 0
    assert report.n_ca_only_residues == 10


def test_ca_only_region_never_reports_a_missing_atom() -> None:
    """The single most important exclusion: a rebuilt region legitimately has only alpha carbons.

    Without it, every rebuilt residue produces findings for N, C and O -- 334 on a rebuilt
    dnmt3a -- and the report is useless.
    """
    report = validate_bonds(ca_only_chain(50))
    assert report.of_kind("missing_atom") == ()
    assert any("alpha carbon and nothing else" in note for note in report.notes)


def test_stretched_ca_ca_bond_is_reported_with_both_residues() -> None:
    structure = ca_only_chain(5)
    structure.xyz[structure.ca_indices[2]] += np.array([2.0, 0.0, 0.0])
    report = validate_bonds(structure)
    violations = report.of_class("ca_ca")
    assert len(violations) == 2, report.describe()
    first = violations[0]
    assert first.kind == "bond_length"
    assert first.residue_labels == ("A:ALA2", "A:ALA3")
    assert first.atoms == ("CA", "CA")
    assert f"{first.measured:.3f}" in first.message
    assert first.message.endswith(".")
    assert first.overshoot > 0.0


def test_coincident_alpha_carbons_are_named_as_such() -> None:
    """v1's own output contains two CA-CA bonds of exactly 0.000 A. That must never be silent."""
    structure = ca_only_chain(4)
    structure.xyz[structure.ca_indices[2]] = structure.xyz[structure.ca_indices[1]]
    report = validate_bonds(structure)
    messages = [v.message for v in report.of_class("ca_ca")]
    assert any("same point" in message for message in messages), messages


def test_rebuilt_ca_ca_bonds_are_held_to_the_length_dodo_builds_to() -> None:
    """A rebuilt region is checked against 3.81 A; preserved geometry gets the wider window.

    The distance used, 3.35 A, is inside the union of the two reference populations (so it passes
    as preserved input) and outside 3.81 +/- 0.20 (so it fails as rebuilt output).
    """
    from dodo.structure import Domain, DomainKind, Span

    distance = 3.35
    assert CA_CA_SHORT_LENGTH - DEFAULT_CA_CA_TOLERANCE < distance < CA_CA_TRANS_LENGTH
    assert abs(distance - CA_CA_BOND_LENGTH) > DEFAULT_CA_CA_TOLERANCE

    structure = ca_only_chain(4, spacing=distance)
    assert validate_bonds(structure).ok, "preserved CA-only geometry inside both populations"

    structure.chains[0].domains.append(
        Domain(structure=structure, span=Span(0, 4), kind=DomainKind.IDR, rebuilt=True)
    )
    report = validate_bonds(structure)
    assert len(report.of_class("ca_ca")) == 3, report.describe()
    assert report.of_provenance("rebuilt") == report.violations


