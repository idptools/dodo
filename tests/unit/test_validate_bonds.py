def two_glycines(*, peptide: float = PEPTIDE_BOND_LENGTH, ca_ca: float | None = None) -> Structure:
    """Two glycines joined by a peptide bond of a given length.

    When ``ca_ca`` is given the second residue is rotated about the peptide nitrogen so that the
    virtual CA-CA distance takes that value while the C-N bond keeps its length -- which is what a
    cis peptide is.
    """
    first = dict(glycine())
    n_ca = reference_length("GLY", "CA", "N")
    nitrogen = np.array([first["C"][0] + peptide, 0.0, 0.0])
    if ca_ca is None:
        alpha = nitrogen + np.array([n_ca, 0.0, 0.0])
    else:
        # Solve for the angle at N that puts CA(2) at the requested distance from CA(1).
        span = nitrogen[0] - first["CA"][0]
        cosine = (span**2 + n_ca**2 - ca_ca**2) / (2 * span * n_ca)
        angle = math.acos(max(-1.0, min(1.0, cosine)))
        # The angle is measured at N from the direction back toward CA(1), which is -x, so the
        # x component is negated. Getting that backwards silently produces a different distance.
        alpha = nitrogen + np.array([-n_ca * math.cos(angle), n_ca * math.sin(angle), 0.0])
    # The rest of residue 2 is built in the frame of its own N-CA bond rather than along +x, so
    # that a cis geometry does not fold its carbonyl back on top of its own nitrogen.
    forward = alpha - nitrogen
    forward = forward / np.linalg.norm(forward)
    sideways = np.cross(forward, np.array([0.0, 0.0, 1.0]))
    sideways = sideways / np.linalg.norm(sideways)
    carbon = alpha + reference_length("GLY", "C", "CA") * forward
    c_o = reference_length("GLY", "C", "O")
    oxygen = carbon + c_o * (
        math.cos(math.radians(60.0)) * forward + math.sin(math.radians(60.0)) * sideways
    )
    second = {
        "N": nitrogen.tolist(),
        "CA": alpha.tolist(),
        "C": carbon.tolist(),
        "O": oxygen.tolist(),
    }
    return build([("GLY", first, "A", 1), ("GLY", second, "A", 2)])


