"""Tests for bond-length validation.

Two halves, deliberately.

The synthetic half places every atom by hand so that each test controls exactly one bond and a
failure names the defect class it broke. The calibration half runs the validator over the six real
fixtures in ``tests/data/structures/`` and over fresh ``dodo.rebuild()`` output, which is the only
way to know whether the tolerances land anywhere useful. Both are needed: a synthetic structure
has no cis-prolines, no unmodelled residues, no strained refinement and no experimental-versus-
predicted systematic offset, so the specific way a bond validator fails -- hundreds of findings on
perfectly good input -- is invisible without real data.

Every calibration number asserted here was measured, and the measurement is in the assertion
message so that a future reader can tell drift from breakage.
"""

