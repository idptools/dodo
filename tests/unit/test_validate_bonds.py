def test_oxt_is_never_reported_missing_but_is_checked_when_present() -> None:
    """OXT exists once per chain. Demanding it everywhere would flag every other residue."""
    report = validate_bonds(build([("GLY", glycine(), "A", 1)]))
    assert "OXT" not in {v.atoms[0] for v in report.of_kind("missing_atom")}

    atoms = dict(glycine())
    oxt = reference_length("GLY", "C", "OXT")
    atoms["OXT"] = carbonyl_oxygen(atoms["C"], oxt, sign=-1.0)
    assert validate_bonds(build([("GLY", atoms, "A", 1)])).ok

    atoms["OXT"] = [atoms["C"][0] + 1.8, 0.6, 0.0]
    stretched = validate_bonds(build([("GLY", atoms, "A", 1)]))
    assert any(v.atoms == ("C", "OXT") for v in stretched.violations), stretched.describe()


