def test_stretched_intra_residue_bond_names_the_bond_and_the_range() -> None:
    structure = build([("GLY", glycine(), "A", 7)])
    stretch_bond(structure, 0, "C", "O", 1.75)
    report = validate_bonds(structure)
    assert len(report.violations) == 1, report.describe()
    violation = report.violations[0]
    assert violation.kind == "bond_length"
    assert violation.bond_class == "intra_residue"
    assert violation.atoms == ("C", "O")
    assert violation.residue_labels == ("A:GLY7",)
    assert violation.measured == pytest.approx(1.75, abs=1e-6)
    assert violation.expected == pytest.approx(reference_length("GLY", "C", "O"), abs=1e-9)
    assert "A:GLY7" in violation.message
    assert "1.750" in violation.message
    assert violation.message.endswith(".")
    assert violation.deviation_sigma > 6.0


def test_tolerance_window_edges_are_respected() -> None:
    """Just inside the accepted window passes; just outside it does not.

    The window is recomputed here from the reference table rather than hardcoded, so this test
    tracks the tolerance definition instead of pinning a magic number.
    """
    low, high = accepted_window("GLY", "C", "O")
    for length, expected_ok in ((high - 1e-4, True), (high + 1e-3, False), (low - 1e-3, False)):
        structure = build([("GLY", glycine(), "A", 1)])
        stretch_bond(structure, 0, "C", "O", length)
        report = validate_bonds(structure)
        assert report.ok is expected_ok, f"{length:.4f} A against {low:.4f}-{high:.4f}"


def test_absolute_tolerance_is_a_floor_not_a_replacement() -> None:
    """Check that the floor applies with the sigma term switched off.

    The floor is what protects the tightest reference distributions from becoming unreasonably
    strict, so it has to be a floor and not a replacement.
    """
    _, high = accepted_window("GLY", "C", "O", sigma=0.0)
    inside = build([("GLY", glycine(), "A", 1)])
    stretch_bond(inside, 0, "C", "O", high - 1e-4)
    assert validate_bonds(inside, tolerance_sigma=0.0).ok

    outside = build([("GLY", glycine(), "A", 1)])
    stretch_bond(outside, 0, "C", "O", high + 0.01)
    assert not validate_bonds(outside, tolerance_sigma=0.0).ok
    # And the floor is doing the work: with no floor either, the same bond is far outside.
    assert not validate_bonds(inside, tolerance_sigma=0.0, absolute_tolerance=1e-6).ok


@pytest.mark.parametrize("name", ACYCLIC_RESIDUES)
def test_every_acyclic_residue_type_at_reference_geometry_is_clean(name: str) -> None:
    """No residue type, side chains included, may be flagged when built to the reference.

    This is the false-positive guard for the intra-residue table itself: 15 residue types and
    every one of their bonds, checked against the very numbers they were built from.
    """
    report = validate_bonds(build([(name, residue_at_reference(name), "A", 1)]))
    assert report.ok, report.describe()
    assert report.n_intra_checked == len(RESIDUE_BONDS[name]) - 1  # OXT is absent


@pytest.mark.parametrize(
    ("residue", "anchor", "moved"),
    [
        ("LYS", "CE", "NZ"),  # four bonds out along the side chain
        ("ARG", "CZ", "NH2"),  # the guanidinium tip
        ("MET", "SD", "CE"),  # a sulfur bond, whose reference length is 1.79 not 1.53
        ("THR", "CB", "OG1"),  # a hydroxyl
        ("ILE", "CG1", "CD1"),  # a branched aliphatic terminus
    ],
)
def test_side_chain_bonds_are_checked_not_just_the_backbone(
    residue: str, anchor: str, moved: str
) -> None:
    """The explicit ask: every bond, not just the backbone."""
    structure = build([(residue, residue_at_reference(residue), "A", 11)])
    _, high = accepted_window(residue, anchor, moved)
    stretch_bond(structure, 0, anchor, moved, high + 0.1)
    report = validate_bonds(structure)
    assert len(report.violations) == 1, report.describe()
    violation = report.violations[0]
    assert violation.atoms == tuple(sorted((anchor, moved)))
    assert violation.bond_class == "intra_residue"
    assert f"A:{residue}11" in violation.message


