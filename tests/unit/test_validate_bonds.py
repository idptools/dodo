#: Measured violation counts on every fixture, unmodified, at the default tolerances.
#:
#: These are pinned so a tolerance change has to be deliberate. What each number is:
#:
#: arf19, dnmt3a, p300 -- AlphaFold models, which is what the reference was measured from and
#: what DODO is built for. arf19 is perfectly clean. dnmt3a's 3 findings are all one residue,
#: A:HIS613, whose imidazole ring is modelled with ND1-CE1 at 2.14 A instead of 1.33 A. p300's 22
#: are 8 residues with the same class of defect plus one MET whose CA-CB is 3.08 A.
#:
#: 6kn7 -- an experimental EM structure, and the reference is AlphaFold-derived. Its 287 findings
#: are 247 distinct residues (3.2% of them), overshooting the accepted window by a median of
#: 0.011 A and at most 0.119 A, dominated by aliphatic side-chain C-C bonds. That is the
#: systematic experiment-versus-prediction difference reference.py documents, not a bug.
#:
#: test.pdb -- not a protein: a 1.5 A-spaced point dump written as CA records by a pre-rewrite
#: debug path. 6,478 of its 7,990 virtual bonds are outside any plausible range, three of them
#: over 200 A. Reporting it as broken is correct.
#:
#: testing_translation.pdb -- pre-rewrite DODO output, and the only fixture with a mix of
#: all-atom and CA-only regions. Its 7 findings are the 4 real defects v2 exists to prevent (two
#: CA-CA bonds of exactly 0.000 A where a region was grafted onto the wrong anchor, and two of
#: 56.2 and 53.8 A where it flew off) plus the same HIS613 ring as dnmt3a, which it inherited.
FIXTURE_VIOLATIONS = {
    "arf19.pdb": 0,
    "dnmt3a.pdb": 3,
    "p300.pdb": 22,
    "6kn7.pdb": 287,
    "test.pdb": 6478,
    "testing_translation.pdb": 7,
}


@pytest.mark.parametrize("name", sorted(FIXTURE_VIOLATIONS))
def test_fixture_violation_counts_are_stable(name: str) -> None:
    report = validate_bonds(read_structure(DATA / name))
    assert len(report.violations) == FIXTURE_VIOLATIONS[name], (
        f"{name}: measured {len(report.violations)} violations, expected "
        f"{FIXTURE_VIOLATIONS[name]}.\n{report.describe(max_violations=5)}"
    )


def test_alphafold_fixtures_are_essentially_clean() -> None:
    """The usability bar: the flag rate on real input must be low enough to read.

    Measured over the three AlphaFold fixtures, 0.081% of 30,500 intra-residue and peptide bonds.
    A validator that flags a few percent of real structures is not usable, and that is what the
    naive symmetric-window and tighter-floor variants did (up to 4.0% on 6kn7).
    """
    checked = 0
    flagged = 0
    for name in ("arf19.pdb", "dnmt3a.pdb", "p300.pdb"):
        report = validate_bonds(read_structure(DATA / name))
        checked += report.n_intra_checked + report.n_peptide_checked
        flagged += len(report.violations)
    rate = flagged / checked
    assert rate < 0.002, f"flagged {flagged} of {checked} bonds ({100 * rate:.3f}%)"


def test_experimental_fixture_findings_are_small_and_local() -> None:
    """Check that the experimental fixture's findings are small and local.

    6kn7 flags more than the predicted fixtures do, and that is expected -- but the findings have
    to be individually small, which is real strain, rather than gross, which would be a broken
    structure or a broken validator.
    """
    report = validate_bonds(read_structure(DATA / "6kn7.pdb"))
    overshoot = np.array([v.overshoot for v in report.violations])
    assert overshoot.max() < 0.2, "no 6kn7 bond is grossly wrong, only strained"
    assert float(np.median(overshoot)) < 0.03
    assert len(report.violating_residues) / report.n_residues < 0.05
    assert report.of_kind("missing_atom") == ()
    assert report.of_kind("unexpected_contact") == ()
    assert report.of_kind("chain_break") == ()


