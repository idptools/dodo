def test_atoms_placed_on_top_of_each_other_are_reported() -> None:
    atoms = dict(glycine())
    # Put the carbonyl oxygen 1.40 A from the amide nitrogen, which is not a bond of any residue.
    # Its own C-O bond is stretched too, and that is reported separately -- one finding per defect.
    atoms["O"] = [atoms["N"][0], 1.40, 0.0]
    report = validate_bonds(build([("GLY", atoms, "A", 3)]))
    contacts = report.of_kind("unexpected_contact")
    assert len(contacts) == 1, report.describe()
    assert set(contacts[0].atoms) == {"N", "O"}
    assert contacts[0].measured < BOND_CUTOFF
    assert "A:GLY3" in contacts[0].message
    assert "on top of each other" in contacts[0].message


def test_hydrogens_do_not_produce_unexpected_contacts() -> None:
    """Check that hydrogens are skipped by the unexpected-contact search.

    The reference table has no hydrogen bonds, so an X-H bond at 1.0 A would be reported as a
    coincidence -- one finding per hydrogen. DODO's readers drop hydrogens, but a hand-built
    Structure can still carry them.
    """
    atoms = dict(glycine())
    atoms["HA"] = [0.0, 1.0, 0.0]
    structure = build([("GLY", atoms, "A", 1)])
    structure.element[list(structure.atom_name).index("HA")] = "H"
    assert validate_bonds(structure).of_kind("unexpected_contact") == ()


def test_bonded_pairs_are_not_unexpected_contacts() -> None:
    """Every real bond is inside the cutoff, so a naive version of this check flags all of them."""
    report = validate_bonds(read_structure(DATA / "arf19.pdb"))
    assert report.of_kind("unexpected_contact") == (), report.describe()


